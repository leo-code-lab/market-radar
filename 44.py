def daily_financial_education_report():
    report_lines = []
    
    def log(text=""):
        print(text)
        report_lines.append(text)

    # 根据当年的天数进行循环索引，确保每天收到不同的课程，不重复
    day_of_year = datetime.now().timetuple().tm_yday
    lesson_index = (day_of_year - 1) % len(FINANCE_LESSONS)
    today_lesson = FINANCE_LESSONS[lesson_index]

    log("=" * 80)
    log(f" ☕ 每天 1 分钟财经小白修炼手册 ({datetime.now().strftime('%Y-%m-%d')})")
    log("=" * 80)
    log(f"\n📌 今日学习主题：{today_lesson['title']}")
    log("-" * 80)
    log(f"\n【通俗概念】\n{today_lesson['concept']}")
    log(f"\n【历史真实案例与启示】\n{today_lesson['history']}")
    log("\n" + "=" * 80)
    log("💡 理财寄语：投资理财是一场认知的修炼。每天吸收一点点，远离韭菜，理性前行！")
    log("=" * 80)

    # 触发邮件发送
    full_report_text = "\n".join(report_lines)
    send_email_report(full_report_text)

